package main

import (
	"fmt"
	"os"
	"strings"

	goimports "golang.org/x/tools/imports"
)

// saveGo formats go source, removes unused imports and saves file.
// Broken source is saved as is to see the error in place
func saveGo(filename string, src []byte) {
	res, err := goimports.Process(filename, src, &goimports.Options{Comments: true, TabIndent: true, TabWidth: 8})
	if err != nil {
		fmt.Println("go format:", filename, err)
		res = src
	}
	saveFile(filename, res)
}

func saveFile(filename string, data []byte) {
	if err := os.WriteFile(filename, data, 0o644); err != nil {
		fmt.Println("save:", filename, err)
	}
}

func fileExists(filename string) bool {
	_, err := os.Stat(filename)
	return err == nil
}

// removeGenerated deletes file of previous versions of generator
func removeGenerated(filename string) {
	b, err := os.ReadFile(filename)
	if err == nil && strings.HasPrefix(string(b), "// Code generated by jayson") {
		os.Remove(filename)
	}
}
