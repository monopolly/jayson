package main

import (
	"fmt"
	"slices"
	"sort"
	"strings"
)

func sortStrings(v []string) { sort.Strings(v) }

// sql groups of fields in declaration order: unique="group", idx="group", search="group"
type sqlGroups struct {
	names  []string
	fields map[string][]string
}

func (a *sqlGroups) add(group, field string) {
	if a.fields == nil {
		a.fields = map[string][]string{}
	}
	if a.fields[group] == nil {
		a.names = append(a.names, group)
	}
	a.fields[group] = append(a.fields[group], field)
}

func (a *sqlGroups) sorted() []string {
	res := slices.Clone(a.names)
	sort.Strings(res)
	return res
}

// primary key columns: sql{primary}
func sqlPrimaryKeys() (res []string) {
	for _, x := range fields {
		if x.SQL.Skip || !x.SQL.Primary {
			continue
		}
		res = append(res, x.SQL.Name)
	}
	return
}

// column definition: bigint not null default 0
func sqlColumnDDL(x *Field, primary []string) string {

	var line []string

	switch {
	case x.SQL.Inc:
		line = append(line, "bigint generated by default as identity")
		if len(primary) == 0 {
			line = append(line, "primary key")
		}
	case x.SQL.Replace != "":
		line = append(line, x.SQL.Replace)
	default:
		line = append(line, x.SQL.Type)
	}

	if x.SQL.NotNull {
		line = append(line, "not null")
	}
	if x.SQL.Append != "" {
		line = append(line, x.SQL.Append)
	}
	if x.SQL.Default.Value != "" {
		line = append(line, x.SQL.Default.Value)
	}

	// single primary key
	if x.SQL.Primary && len(primary) == 1 && !strings.Contains(strings.Join(line, " "), "primary key") {
		line = append(line, "primary key")
	}

	return strings.Join(line, " ")
}

// create table and indexes from tags
func sqlDDL() (create string, indexes []sqlIndex) {

	table := settings.SQL.Table
	primary := sqlPrimaryKeys()

	var pad int
	for _, x := range fields {
		pad = max(pad, len(x.SQL.Name))
	}
	column := func(name, ddl string) string {
		return fmt.Sprintf("\t%s%s%s", name, strings.Repeat(" ", pad+5-len(name)), ddl)
	}

	var lines []string
	var unique, group, search sqlGroups

	for _, x := range fields {
		if x.SQL.Skip {
			continue
		}

		lines = append(lines, column(x.SQL.Name, sqlColumnDDL(x, primary)))

		for _, g := range x.SQL.Unique {
			unique.add(g, x.SQL.Name)
		}
		for _, g := range x.SQL.Index.Group {
			group.add(g, x.SQL.Name)
		}
		for _, g := range x.SQL.Index.Search {
			search.add(g, x.SQL.Name)
		}

		// simple index: sql{index}
		if !x.SQL.Index.Simple {
			continue
		}
		switch {
		case x.SQL.Array:
			name := fmt.Sprintf("gin_%s_%s", settings.Origin, x.SQL.Name)
			indexes = append(indexes, sqlIndex{
				Name: name,
				SQL:  fmt.Sprintf("create index if not exists %s on %s using gin(%s)", name, table, x.SQL.Name),
				Help: fmt.Sprintf("select * from %s where %s @> array[1]", table, x.SQL.Name),
			})
		case x.SQL.Type == "jsonb":
			name := fmt.Sprintf("gin_%s_%s", settings.Origin, x.SQL.Name)
			indexes = append(indexes, sqlIndex{
				Name: name,
				SQL:  fmt.Sprintf("create index if not exists %s on %s using gin(%s)", name, table, x.SQL.Name),
				Help: fmt.Sprintf(`select * from %s where %s @> '{"year": 2020}'`, table, x.SQL.Name),
			})
		default:
			name := fmt.Sprintf("idx_%s_%s", settings.Origin, x.SQL.Name)
			indexes = append(indexes, sqlIndex{
				Name: name,
				SQL:  fmt.Sprintf("create index if not exists %s on %s (%s)", name, table, x.SQL.Name),
			})
		}
	}

	// tsvector column: search="group"
	for _, g := range search.names {
		var text []string
		for _, name := range search.fields[g] {
			text = append(text, fmt.Sprintf("coalesce(%s::text, '')", name))
		}
		lines = append(lines, column(g, fmt.Sprintf("tsvector generated always as (to_tsvector('simple', %s)) stored", strings.Join(text, " || ' ' || "))))
	}

	// unique constrains: unique="group"
	for _, g := range unique.sorted() {
		lines = append(lines, fmt.Sprintf("\tunique (%s)", strings.Join(unique.fields[g], ", ")))
	}

	// composite primary key
	if len(primary) > 1 {
		lines = append(lines, fmt.Sprintf("\tprimary key (%s)", strings.Join(primary, ", ")))
	}

	create = fmt.Sprintf("create table if not exists %s (\n%s\n)", table, strings.Join(lines, ",\n"))

	// group index: idx="group"
	for _, g := range group.sorted() {
		name := fmt.Sprintf("idx_%s_%s", settings.Origin, g)
		indexes = append(indexes, sqlIndex{
			Name: name,
			SQL:  fmt.Sprintf("create index if not exists %s on %s (%s)", name, table, strings.Join(group.fields[g], ", ")),
		})
	}

	// tsvector index: search="group"
	for _, g := range search.sorted() {
		name := fmt.Sprintf("gin_%s_%s", settings.Origin, g)
		indexes = append(indexes, sqlIndex{
			Name: name,
			SQL:  fmt.Sprintf("create index if not exists %s on %s using gin(%s)", name, table, g),
			Help: fmt.Sprintf("select * from %s where %s @@ websearch_to_tsquery('simple', 'text')", table, g),
		})
	}

	return
}

// .sql file: table, indexes, migrations from tags sql{ver="2"}, sql{renames="old"}
func sqlFile() []byte {

	table := settings.SQL.Table
	create, indexes := sqlDDL()

	var list []string
	list = append(list, fmt.Sprintf("--drop table %s;", table))
	list = append(list, create+";", "")

	if len(indexes) > 0 {
		list = append(list, "--indexes")
		for _, x := range indexes {
			list = append(list, fmt.Sprintf("--drop index %s;", x.Name))
			if x.Help != "" {
				list = append(list, fmt.Sprintf("--ex: %s;", x.Help))
			}
			list = append(list, x.SQL+";", "")
		}
	}

	// migrations: new columns by version, renames
	var versions sqlGroups
	var renames []string
	primary := sqlPrimaryKeys()
	for _, x := range fields {
		if x.SQL.Skip {
			continue
		}
		if x.SQL.AlterTable != "" {
			versions.add(x.SQL.AlterTable, fmt.Sprintf("alter table %s add column if not exists %s %s;", table, x.SQL.Name, sqlColumnDDL(x, primary)))
		}
		if x.SQL.Rename != "" {
			renames = append(renames, fmt.Sprintf("alter table %s rename column %s to %s;", table, x.SQL.Rename, x.SQL.Name))
		}
	}

	if len(versions.names) > 0 {
		list = append(list, "--alter table")
		for _, v := range versions.sorted() {
			list = append(list, fmt.Sprintf("--%s", v))
			list = append(list, versions.fields[v]...)
		}
		list = append(list, "")
	}

	if len(renames) > 0 {
		list = append(list, "--rename")
		list = append(list, renames...)
		list = append(list, "")
	}

	return []byte(strings.Join(list, "\n"))
}
